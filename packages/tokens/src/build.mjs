// Style Dictionary reads the DTCG files named by the resolver, once per theme,
// and transforms them to CSS values. Style Dictionary does not implement the
// DTCG resolver module itself, so this file walks it.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';

const dir = fileURLToPath(new URL('../tokens/', import.meta.url));
const dist = new URL('../dist/', import.meta.url);
const EXT = 'design-system.css';

const resolver = JSON.parse(readFileSync(`${dir}tokens.resolver.json`, 'utf8'));
const foundation = resolver.sets.foundation.sources.map((s) => dir + s.$ref);
const contexts = resolver.modifiers.theme.contexts;

const dimension = (v) => `${v.value}${v.unit}`;
const unitless = (v) => {
  const s = String(v);
  return s.includes('.') && s.split('.')[1].length === 1 ? v.toFixed(2) : s;
};

const cssValue = (token) => {
  const { $type: type, $value: value, $extensions: ext, path } = token;
  if (ext?.[EXT]) return ext[EXT];
  if (type === 'color') return value.hex;
  if (type === 'dimension' || type === 'duration') return dimension(value);
  if (type === 'cubicBezier') return `cubic-bezier(${value.join(', ')})`;
  if (type === 'fontFamily') return value.map((f, i) => (i === 0 ? `'${f}'` : f)).join(', ');
  if (path[0] === 'tracking') return value === 0 ? '0' : `${value}em`;
  if (path[0] === 'leading') return unitless(value);
  return String(value);
};

StyleDictionary.registerTransform({
  name: 'ds/css-value',
  type: 'value',
  transitive: true,
  filter: () => true,
  transform: cssValue,
});

const read = async (mode) => {
  const sd = new StyleDictionary({
    source: [...foundation, ...contexts[mode].map((s) => dir + s.$ref)],
    log: { warnings: 'error', verbosity: 'silent' },
    platforms: { css: { transforms: ['ds/css-value'] } },
  });
  const { allTokens } = await sd.getPlatformTokens('css');
  return allTokens;
};

const light = await read('light');
const dark = await read('dark');

// The token path is the CSS name, verbatim: c.chart-1 is --c-chart-1. Taken from
// the path because Style Dictionary skips name transforms on aliased tokens.
const lines = (tokens, indent = '    ') => tokens.map((t) => `${indent}--${t.path.join('-')}: ${t.$value};`).join('\n');
const inGroup = (tokens, group) => tokens.filter((t) => t.path[0] === group);

const typeScale = inGroup(light, 'text')
  .map((t) => {
    const k = t.path[1];
    const of = (g) => inGroup(light, g).find((x) => x.path[1] === k).$value;
    return `    --text-${k}: ${t.$value};\n    --leading-${k}: ${of('leading')};\n    --tracking-${k}: ${of('tracking')};`;
  })
  .join('\n');

const css = `/* Generated by Style Dictionary from the DTCG files in packages/tokens/tokens.
 * Ramps are built in OKLCH and gamut-clipped to sRGB. Do not edit by hand:
 * check.mjs asserts every colour pairing and the build exits non-zero on failure.
 */

:root {
    /* families */
${lines(inGroup(light, 'font'))}

    /* spacing — 4-based, ten steps, no exceptions */
${lines(inGroup(light, 'sp'))}

    /* radius — pair with corner-shape: superellipse(2) for Figma smoothing */
${lines(inGroup(light, 'radius'))}

    /* layout */
${lines(inGroup(light, 'layout'))}

    /* type scale */
${typeScale}

    /* motion */
${lines(inGroup(light, 'motion'))}
${lines(inGroup(light, 'ease'))}

    /* colour — light */
${lines(inGroup(light, 'c'))}
    color-scheme: light;
}

:root[data-theme="dark"] {
${lines(inGroup(dark, 'c'))}
    color-scheme: dark;
}

@media (prefers-color-scheme: dark) {
    :root:not([data-theme="light"]) {
${lines(inGroup(dark, 'c'))}
        color-scheme: dark;
    }
}

${readFileSync(new URL('./base.css', import.meta.url), 'utf8')}`;

// Tokens Studio shape, for the Figma round-trip.
const flat = (tokens, type) =>
  Object.fromEntries(tokens.map((t) => [t.path.slice(1).join('.'), { value: t.$value, type }]));
const prim = (name) =>
  flat(inGroup(light, 'primitive').filter((t) => t.path[1] === name).map((t) => ({ ...t, path: t.path.slice(1) })), 'color');
const chartPrim = {
  light: flat(inGroup(light, 'primitive').filter((t) => t.path[1] === 'chart' && t.path[2] === 'light').map((t) => ({ ...t, path: t.path.slice(2) })), 'color'),
  dark: flat(inGroup(light, 'primitive').filter((t) => t.path[1] === 'chart' && t.path[2] === 'dark').map((t) => ({ ...t, path: t.path.slice(2) })), 'color'),
};
const scaleGroup = (group, type) => flat(inGroup(light, group), type);
const typeGroup = Object.fromEntries(
  inGroup(light, 'text').map((t) => {
    const k = t.path[1];
    const of = (g) => inGroup(light, g).find((x) => x.path[1] === k);
    const family = { display: 'display', mono: 'mono' };
    const fam = ['display-xl', 'display', 'h2', 'h3'].includes(k) ? 'display' : k === 'mono' ? 'mono' : 'body';
    return [k, {
      value: {
        fontSize: t.$value,
        lineHeight: of('leading').$value,
        letterSpacing: of('tracking').$value,
        fontFamily: inGroup(light, 'font').find((x) => x.path[1] === (family[fam] ?? 'body')).$value,
      },
      type: 'typography',
    }];
  }),
);
const studio = {
  primitive: {
    neutral: prim('neutral'), accent: prim('accent'), success: prim('success'), danger: prim('danger'),
    warning: prim('warning'), serious: prim('serious'), chart: chartPrim, seq: prim('seq'), seq2: prim('seq2'),
  },
  light: { color: flat(inGroup(light, 'c'), 'color') },
  dark: { color: flat(inGroup(dark, 'c'), 'color') },
  scale: {
    space: scaleGroup('sp', 'spacing'),
    radius: scaleGroup('radius', 'borderRadius'),
    layout: scaleGroup('layout', 'sizing'),
    type: typeGroup,
  },
};

const values = {
  light: Object.fromEntries(inGroup(light, 'c').map((t) => [t.path[1], t.$value])),
  dark: Object.fromEntries(inGroup(dark, 'c').map((t) => [t.path[1], t.$value])),
};

mkdirSync(dist, { recursive: true });
writeFileSync(new URL('tokens.css', dist), css);
writeFileSync(new URL('tokens-studio.json', dist), JSON.stringify(studio, null, 2) + '\n');
writeFileSync(new URL('values.json', dist), JSON.stringify(values, null, 2) + '\n');
console.log(`Style Dictionary: ${light.length} light and ${dark.length} dark tokens. Wrote dist/.`);
